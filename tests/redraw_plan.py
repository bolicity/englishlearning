groups = []
n = 0
def add_group(mu_base, four, bg):
    global n
    n += 1
    token = f"重画{n:02d}"
    prompt = (f"{token}：{STYLE}。2×2四格布局，四格之间用细墨线分隔，每格一个完整场景，"
              f"四格各自独立成画。{bg}。{RU}。"
              f"左上格：{four[0]}；右上格：{four[1]}；左下格：{four[2]}；右下格：{four[3]}；"
              f"画面中不出现任何文字或水印。")
    groups.append({'mu': mu_base, 'token': token, 'prompt': prompt, 'quads': [f"{mu_base}-c{i}" for i in (1, 2, 3, 4)]})

