TAIL = '画面中不出现任何文字或水印。'

def main():
    quads = []
    for key, (name, scenes, caps) in ROWS.items():
        for i, (s, c) in enumerate(zip(scenes, caps), start=2):
            quads.append({'img': f'{key}-b{i}', 'row': key, 'name': name, 'cap': c, 'scene': s})

    groups = []
    for gi in range(0, len(quads), 4):
        chunk = quads[gi:gi + 4]
        token = f'扩图{len(groups)+1:02d}'
        slots = ['左上格', '右上格', '左下格', '右下格']
        body = ''.join(f'{slots[i]}：{q["scene"]}；' for i, q in enumerate(chunk))
        groups.append({
            'mu': f'mu-ext-{len(groups)+1:02d}',
            'token': token,
            'prompt': f'{token}：{HEAD}{body}{TAIL}',
            'quads': chunk,
        })
    manifest = {'groups': groups, 'total_quads': len(quads)}
    out = '/tmp/comics_expand_manifest.json'
    with open(out, 'w', encoding='utf-8') as f:
        json.dump(manifest, f, ensure_ascii=False, indent=1)
    print(f'行数 {len(ROWS)}，新增格 {len(quads)}，母图 {len(groups)} 张 -> {out}')
